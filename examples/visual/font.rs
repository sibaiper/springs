/// Rows for `c`, or `None` if the font has no glyph for it.
pub fn glyph(c: char) -> Option<[u8; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(candidate, _)| *candidate == c)
        .map(|(_, rows)| *rows)
}

/// Width of `text` when drawn at `scale`, in pixels.
pub fn width(text: &str, scale: i32) -> i32 {
    (text.chars().count() as i32 * ADVANCE - 1).max(0) * scale
}
